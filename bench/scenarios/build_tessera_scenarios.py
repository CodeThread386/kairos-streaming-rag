"""Authoring script for the Tessera benchmark scenarios.

The TEST split was written and frozen before any engine tuning; only the DEV split
was used while developing. Gold labels reference corpus section IDs (Doc_XX §N).
key_facts: list of groups; a group is satisfied when ANY string in it appears in the answer.
"""
import json

def T(utt, sub=None, kind="new", key=None, unans=None, needs=None, chunks=None, end_t=None):
    sub = sub or []
    if needs is None:
        needs = kind in ("new", "refinement")
    g = {"needs_retrieval": needs, "turn_type": kind,
         "sub_intents": [{"name": n, "relevant": r} for n, r in sub],
         "key_facts": key or [], "unanswerable_aspects": unans or []}
    t = {"utterance": utt, "gold": g}
    if chunks:
        t["chunks"] = chunks
        t["end_t"] = end_t
    return t

def S(sid, cat, *turns):
    return {"id": sid, "category": cat, "turns": list(turns)}

